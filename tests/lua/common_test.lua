-- Adapter helpers: text cleaning, JSON decoding, money/job/gang/grade
-- parsing, plates and vehicle states (plan §2, §2.10).

local c = Aptic.common

test('clean_text trims, turns control characters into spaces and drops invalid UTF-8', function()
  eq(c.clean_text('  Marcus  ', 120), 'Marcus')
  eq(c.clean_text('Star\nLight', 120), 'Star Light')
  eq(c.clean_text('A\0B', 120), 'A B')
  eq(c.clean_text('Bad\xff\xfeByte', 120), 'BadByte')
  eq(c.clean_text('\xc0\xafoverlong', 120), 'overlong')
  eq(c.clean_text('\u{00A0}\u{3000}Zoë\u{FEFF}', 120), 'Zoë', 'JS whitespace trimmed')
  eq(c.clean_text('   ', 120), nil)
  eq(c.clean_text('', 120), nil)
  eq(c.clean_text(nil, 120), nil)
  eq(c.clean_text({}, 120), nil)
  eq(c.clean_text(42, 120), '42')
  eq(c.clean_text(0 / 0, 120), nil)
end)

test('clean_text cuts by UTF-16 units on a code point boundary (emoji count 2)', function()
  local star = '\u{1F31F}'
  eq(c.utf16_len_cps(c.codepoints(star)), 2)
  eq(c.clean_text(('a'):rep(119) .. star, 120), ('a'):rep(119), 'emoji would make 121')
  eq(c.clean_text(('a'):rep(118) .. star, 120), ('a'):rep(118) .. star)
  eq(c.clean_text('abc def', 4), 'abc', 'no trailing space after the cut')
end)

test('decode accepts JSON text and already-decoded tables, and reports bad input', function()
  eq(c.decode('{"cash":1}').cash, 1)
  local t = { cash = 2 }
  eq(c.decode(t), t)
  local v, why = c.decode('{not json')
  eq(v, nil)
  eq(why, 'malformed')
  v, why = c.decode(nil)
  eq(why, 'missing')
  v, why = c.decode('')
  eq(why, 'missing')
  v, why = c.decode('"just a string"')
  eq(why, 'malformed')
end)

test('number, integer and epoch accept numeric strings and refuse the rest', function()
  eq(c.number('12.5'), 12.5)
  eq(c.number('abc'), nil)
  eq(c.number(1 / 0), nil)
  eq(math.type(c.integer(3.0)), 'integer')
  eq(c.integer(3.5), nil)
  eq(c.epoch('1794344700.000000'), 1794344700)
  eq(c.epoch(0), nil)
  eq(c.epoch(nil), nil)
end)

test('parse_job reads the JSON shape, a bare-number grade and a string level', function()
  local name, level, problem = c.parse_job({ name = 'police', grade = { name = 'Sergeant', level = 2 } })
  eq(name, 'police'); eq(level, 2); eq(problem, nil)
  name, level = c.parse_job({ name = 'police', grade = 1 })
  eq(level, 1)
  name, level = c.parse_job({ name = 'mechanic', grade = { level = '3' } })
  eq(level, 3)
  eq(math.type(level), 'integer')
end)

test('parse_job falls back to unemployed 0 and says why', function()
  local name, level, problem = c.parse_job(nil)
  eq(name, 'unemployed'); eq(level, 0); eq(problem, 'job_unreadable')
  name, level, problem = c.parse_job({ grade = 1 })
  eq(problem, 'job_unreadable')
  name, level, problem = c.parse_job({ name = 'police', grade = { level = -1 } })
  eq(name, 'police'); eq(level, 0); eq(problem, 'job_grade_unreadable')
  name, level, problem = c.parse_job({ name = 'police', grade = { level = 2.5 } })
  eq(problem, 'job_grade_unreadable')
end)

test('parse_gang: none and missing mean no gang', function()
  eq(c.parse_gang({ name = 'ballas' }), 'ballas')
  eq(c.parse_gang({ name = 'none' }), nil)
  eq(c.parse_gang(nil), nil)
  eq(c.parse_gang({}), nil)
end)

test('parse_money keeps signed amounts and custom codes, sorted', function()
  local list, problems = c.parse_money({ cash = 350, bank = -2350, crypto = 0, casino_chips = 500 })
  eq(#problems, 0)
  eq(#list, 4)
  eq(list[1].currency, 'bank'); eq(list[1].amount, -2350)
  eq(list[2].currency, 'cash')
  eq(list[3].currency, 'casino_chips')
  eq(list[4].currency, 'crypto')
end)

test('parse_money lowercases, renames and skips codes, and refuses codes the contract cannot take', function()
  local list, problems = c.parse_money(
    { BlackMoney = 120, ['dirty-money'] = 40, gold = 'lots', [1] = 5, bank = 10, Bank = 99, casino = 7 },
    { blackmoney = 'dirty' }, { casino = true })
  local got = {}
  for _, b in ipairs(list) do got[b.currency] = b.amount end
  eq(got.dirty, 120, 'renamed')
  eq(got.bank, 10, 'the exact lowercase key wins over Bank')
  eq(got.casino, nil, 'skipped by config')
  eq(got['dirty-money'], nil)
  table.sort(problems)
  eq(table.concat(problems, ','), 'amount_unreadable,currency_code_invalid,currency_code_invalid,currency_duplicate')
end)

test('parse_money on a missing table gives nothing', function()
  local list, problems = c.parse_money(nil)
  eq(#list, 0); eq(#problems, 0)
end)

test('grades: string or integer keys, sparse levels kept, missing names defaulted, bad keys dropped', function()
  local g, problems = c.grades({ ['0'] = { name = 'Recruit' }, ['1'] = { name = 'Novice' }, ['3'] = { name = 'Owner' },
    boss = { name = 'x' }, ['-1'] = { name = 'y' } })
  eq(#g, 3)
  eq(g[1].level, 0); eq(g[2].level, 1); eq(g[3].level, 3)
  eq(math.type(g[3].level), 'integer')
  eq(#problems, 2)
  local q = c.grades({ [0] = { name = 'Recruit' }, [3] = { payment = 120 } })
  eq(q[2].name, 'Grade 3')
  eq(getmetatable(c.grades(nil)), c.ARRAY_MT, 'an empty list is still marked as an array')
  eq(json.encode(c.grades({})), '[]')
end)

test('plates are trimmed, uppercased and limited to 32', function()
  eq(c.plate(' jun 77 '), 'JUN 77')
  eq(c.plate('dupe 01 '), 'DUPE 01')
  eq(c.plate(('A'):rep(32)), ('A'):rep(32))
  eq(c.plate(('A'):rep(33)), nil)
  eq(c.plate('   '), nil)
  eq(c.plate(nil), nil)
  eq(c.plate(12345), '12345')
end)

test('vehicle state codes 0/1/2 map to out/garaged/impounded, anything else is unknown', function()
  eq(c.vehicle_state(0), 'out')
  eq(c.vehicle_state(1), 'garaged')
  eq(c.vehicle_state(2), 'impounded')
  eq(c.vehicle_state('1'), 'garaged')
  eq(c.vehicle_state(3), nil)
  eq(c.vehicle_state(true), nil)
  eq(c.vehicle_state(nil), nil)
end)

test('char_name joins first and last name from charinfo', function()
  eq(c.char_name({ firstname = 'Marcus', lastname = 'Reyes' }, 120), 'Marcus Reyes')
  eq(c.char_name({ firstname = 'Cher' }, 120), 'Cher')
  eq(c.char_name({ firstname = '', lastname = '' }, 120), nil)
  eq(c.char_name(nil, 120), nil)
end)
