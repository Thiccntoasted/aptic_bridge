test('no framework yet: waits, then sends once it starts', function()
  Stub.convars.aptic_api_key = H.KEY
  Stub.convars.aptic_salt = H.SALT
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  eq(#sent, 0)
  eq(Aptic.heartbeat.state.state, 'waiting')
