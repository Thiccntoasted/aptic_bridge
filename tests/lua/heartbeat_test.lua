-- The heartbeat loop, driven with a fake clock and a scripted transport.

local CONTRACT_KEYS = {
  version = true, operation = true, max_clients = true, framework = true, inventory = true,
  agent_version = true, instance_id = true, salt_fp = true, framework_version = true, inventory_version = true,
}

test('the first wake sends a contract-shaped heartbeat', function()
  H.server()
  local sent = H.fake_transport({ H.OK })
  truthy(H.tick(0))
  eq(#sent, 1)
  local req = sent[1]
  eq(req.endpoint, 'https://aptic.dev/api/ingest/v1')
  eq(req.timeout_ms, 15000)
  local p = req.payload
  for k in pairs(p) do truthy(CONTRACT_KEYS[k], 'unexpected field ' .. k) end
  eq(p.version, 1)
  eq(math.type(p.version), 'integer')
  eq(p.operation, 'heartbeat')
  eq(p.agent_version, 'aptic_bridge/0.1.0')
  eq(p.framework, 'qbox')
  eq(p.inventory, 'ox_inventory')
  eq(p.framework_version, '1.24.1')
  eq(p.inventory_version, '2.44.1')
  eq(p.salt_fp, '49224dd5')
  eq(p.max_clients, 48)
  truthy(p.instance_id:match('^[%w_%-]+$') and #p.instance_id >= 8)
end)

test('the request never carries the key or the salt', function()
  H.server()
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  for k, v in pairs(sent[1].payload) do
    not_contains(tostring(v), H.KEY:sub(9), k)
    not_contains(tostring(v), H.SALT, k)
  end
  for k, v in pairs(sent[1]) do
    if type(v) == 'string' then not_contains(v, H.KEY:sub(9), k) end
  end
end)

test('salt_fp is sent only once a salt is pinned; heartbeats run without one', function()
  H.server({ salt = false })
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  eq(#sent, 1, 'heartbeat still sent')
  eq(sent[1].payload.salt_fp, nil)
  contains(Stub.output(), 'set aptic_salt "')
  eq(Aptic.heartbeat.state.state, 'ok')
  local blockers = table.concat(Aptic.heartbeat.snapshot_blockers(), ',')
  contains(blockers, 'salt not pinned')
end)

test('a salt pinned from the live console is picked up on the next heartbeat', function()
  H.server({ salt = false })
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  Stub.convars.aptic_salt = H.SALT
  H.until_sent(70)
  eq(sent[2].payload.salt_fp, '49224dd5')
  contains(Stub.output(), 'Hash salt pinned (fingerprint 49224dd5)')
  eq(#Aptic.heartbeat.snapshot_blockers(), 0)
end)

test('a version the contract would reject is left out of the payload', function()
