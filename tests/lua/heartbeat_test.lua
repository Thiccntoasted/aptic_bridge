test('after ok the next heartbeat comes 55-65 s later, not sooner', function()
  H.server()
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  local waited = H.until_sent(120)
  between(waited, 55, 66)
  eq(#sent, 2)
end)

test('an accepted heartbeat logs once, with versions and key prefix only', function()
  H.server()
  H.fake_transport({ H.OK })
  H.tick(0)
  H.until_sent(70)
  H.until_sent(70)
  local out = Stub.output()
  contains(out, 'heartbeat ok: qbox 1.24.1 + ox_inventory 2.44.1, key apt_ing_TESTkeyA…, endpoint aptic.dev.')
  local _, count = out:gsub('heartbeat ok', '')
  eq(count, 1)
end)

test('server_time gives the clock offset', function()
  H.server()
  local now = os.time()
  H.fake_transport({ { ok = true, status = 200, json = { ok = true, server_time = os.date('!%Y-%m-%dT%H:%M:%S', now + 120) .. '.5+00:00' } } })
  H.tick(0)
  between(Aptic.heartbeat.state.clock_offset_s, 119, 122)
  contains(Stub.output(), 's off Aptic')
end)

test('an older agent than min_agent_version warns to update', function()
  H.server()
