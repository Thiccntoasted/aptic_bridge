  Stub.start('qbx_core', '1.24.1'); Stub.start('ox_inventory', '2.44.1')
  local waited = H.until_sent(40)
  between(waited, 29, 31)
end)

test('Qbox + qb-inventory still heartbeats but blocks snapshots', function()
  H.server({ framework = 'qbox', inventory = 'qb-inventory' })
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  eq(#sent, 1)
  eq(sent[1].payload.inventory, 'qb-inventory')
  contains(table.concat(Aptic.heartbeat.snapshot_blockers(), ','), 'unsupported combination')
end)

test('a transport that is not loaded is a transient failure, not a crash', function()
  H.server()
  Stub.export_overrides.httpPost = function() error('No such export httpPost in resource aptic_bridge') end
  H.tick(0)
  eq(Aptic.heartbeat.state.last.code, 'transport_unavailable')
  eq(Aptic.heartbeat.state.state, 'unavailable')
end)

test('the Lua transport passes the request to the JS export and returns its answer', function()
  local got
  Stub.export_overrides.httpPost = function(request, cb)
    got = request
    cb({ ok = true, status = 200, json = { ok = true } })
  end
  local result = Aptic.transport.post({ endpoint = 'https://aptic.dev/api/ingest/v1', payload = { version = 1 } })
  eq(got.payload.version, 1)
  eq(result.status, 200)
end)

test('the boot thread registers the command and starts the loop', function()
  H.server()
  H.fake_transport({ H.OK })
  eq(#Stub.threads, 1, 'main.lua queued boot')
  Stub.threads[1]()
  truthy(Stub.commands.aptic and Stub.commands.aptic.restricted == true)
  eq(#Stub.threads, 3, 'heartbeat and snapshot threads started')
  contains(Stub.output(), 'aptic_bridge 0.1.0 starting. Framework/inventory: qbox 1.24.1 + ox_inventory 2.44.1.')
end)
