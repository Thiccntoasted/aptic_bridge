test('401 stops all traffic until the key changes, then sends at once', function()
  H.server()
  local sent = H.fake_transport({ H.err(401, 'invalid_credential'), H.OK })
  H.tick(0)
  eq(Aptic.heartbeat.state.state, 'unauthorized')
  eq(H.until_sent(3600), nil, 'nothing sent for an hour with the same key')
  eq(#sent, 1)
  contains(Stub.output(), 'Aptic refused the connection key (invalid_credential)')
  -- The owner pastes the rotated key in the live console.
  Stub.convars.aptic_api_key = H.KEY2
  eq(H.until_sent(5), 1, 'sent on the next wake')
  eq(#sent, 2)
  eq(Aptic.heartbeat.state.state, 'ok')
  contains(Stub.output(), 'aptic_api_key changed (now apt_ing_ROTATEDz…)')
end)

test('a key rotated while healthy is used at once', function()
  H.server()
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  H.tick(5000)
  eq(#sent, 1)
  Stub.convars.aptic_api_key = H.KEY2
  truthy(H.tick(1000))
  eq(#sent, 2)
end)

test('422 adapter_mismatch retries after 10 minutes', function()
  H.server()
  local sent = H.fake_transport({ H.err(422, 'adapter_mismatch') })
  H.tick(0)
  eq(Aptic.heartbeat.state.state, 'adapter_mismatch')
  contains(Stub.output(), 'different framework or inventory than this server runs (qbox 1.24.1 + ox_inventory 2.44.1)')
  local waited = H.until_sent(700)
  eq(waited, 600)
  eq(#sent, 2)
  local _, count = Stub.output():gsub('different framework', '')
  eq(count, 1, 'the same refusal is printed once')
end)

test('422 retries at once when the detected adapter changes', function()
  H.server({ framework = 'qbcore', inventory = 'qb-inventory' })
  local sent = H.fake_transport({ H.err(422, 'adapter_mismatch'), H.OK })
  H.tick(0)
  eq(sent[1].payload.framework, 'qbcore')
  -- The owner swaps to Qbox + ox_inventory.
  Stub.stop('qb-core'); Stub.stop('qb-inventory')
  Stub.start('qbx_core', '1.24.1'); Stub.start('ox_inventory', '2.44.1')
  eq(H.until_sent(5), 1)
  eq(sent[2].payload.framework, 'qbox')
  eq(Aptic.heartbeat.state.state, 'ok')
end)

test('429 waits retry_after from the body', function()
  H.server()
  local sent = H.fake_transport({ H.err(429, 'rate_limited', { retry_after_body = 25, retry_after_header = 60 }), H.OK })
  H.tick(0)
  local waited = H.until_sent(100)
  between(waited, 25, 28)
  eq(#sent, 2)
end)

test('network failures back off 5, 10, 20 ... and success resets', function()
  H.server()
  local fail = { ok = false, status = 0, transport_error = 'timeout' }
  local sent = H.fake_transport({ fail, fail, fail, fail, H.OK, fail })
  H.tick(0)
  local waits = {}
  for i = 1, 4 do waits[i] = H.until_sent(400) end
  between(waits[1], 3, 5)
  between(waits[2], 5, 10)
  between(waits[3], 10, 20)
  between(waits[4], 20, 40)
  eq(Aptic.heartbeat.state.state, 'ok')
  eq(Aptic.heartbeat.state.failures, 0)
  between(H.until_sent(100), 55, 66)
  local after_ok = H.until_sent(10)
  between(after_ok, 3, 5, 'backoff starts from the bottom again')
  local _, count = Stub.output():gsub('Aptic is unreachable', '')
  eq(count, 2, 'one line per outage, not per retry')
end)

test('a missing key sends nothing and looks again every 30 s', function()
  H.server({ key = false })
  local sent = H.fake_transport({ H.OK })
  H.tick(0)
  eq(#sent, 0)
