-- Framework and inventory detection (plan §3.3, D1, D11).

test('Qbox + ox_inventory is supported, with versions from resource metadata', function()
  Stub.start('qbx_core', '1.24.1')
  Stub.start('ox_inventory', 'v2.44.1')
  local cap = Aptic.capability.detect()
  eq(cap.framework, 'qbox')
  eq(cap.framework_resource, 'qbx_core')
  eq(cap.framework_version, '1.24.1')
  eq(cap.inventory, 'ox_inventory')
  eq(cap.inventory_version, '2.44.1', 'leading v dropped')
  eq(cap.support, 'supported')
end)

test('QBCore + qb-inventory is supported', function()
  Stub.start('qb-core', '1.3.0')
  Stub.start('qb-inventory', '2.2.3')
  local cap = Aptic.capability.detect()
  eq(cap.framework, 'qbcore')
  eq(cap.inventory, 'qb-inventory')
  eq(cap.support, 'supported')
end)

test('Qbox + qb-inventory is recognised and unsupported', function()
  Stub.start('qbx_core', '1.24.1')
  Stub.start('qb-inventory', '2.2.3')
  local cap = Aptic.capability.detect()
  eq(cap.framework, 'qbox')
  eq(cap.inventory, 'qb-inventory')
  eq(cap.support, 'unsupported')
  contains(cap.reason, 'Qbox requires ox_inventory')
end)

test('QBCore + ox_inventory is recognised and unsupported (only on request)', function()
  Stub.start('qb-core', '1.3.0')
  Stub.start('ox_inventory', '2.41.0')
  local cap = Aptic.capability.detect()
  eq(cap.support, 'unsupported')
  contains(cap.reason, 'only on request')
end)

test('qbx_core wins when qb-core is also reported started (provide qb-core)', function()
  Stub.start('qb-core', '1.3.0')
  Stub.start('qbx_core', '1.24.1')
  Stub.start('ox_inventory', '2.44.1')
  eq(Aptic.capability.detect().framework, 'qbox')
end)

test('ox_inventory wins when both inventories run', function()
  Stub.start('qbx_core', '1.24.1')
  Stub.start('qb-inventory', '2.2.3')
  Stub.start('ox_inventory', '2.44.1')
  eq(Aptic.capability.detect().inventory, 'ox_inventory')
end)

test('a resource that is only starting, stopped or missing does not count', function()
  Stub.resources['qbx_core'] = { state = 'starting', meta = { version = '1.24.1' } }
  Stub.start('ox_inventory', '2.44.1')
  local cap = Aptic.capability.detect()
  eq(cap.support, 'incomplete')
  eq(cap.framework, nil)
  contains(cap.reason, 'framework')
  Stub.start('qbx_core', '1.24.1')
  eq(Aptic.capability.detect().support, 'supported', 'picked up once started')
  Stub.stop('ox_inventory')
  local after = Aptic.capability.detect()
  eq(after.support, 'incomplete')
  contains(after.reason, 'inventory')
end)

test('nothing started at all', function()
  local cap = Aptic.capability.detect()
  eq(cap.support, 'incomplete')
  eq(Aptic.capability.describe(cap), 'none detected')
end)

test('versions the contract would reject are left out, not sent', function()
  local clean = Aptic.capability.clean_version
  eq(clean('1.24.1'), '1.24.1')
  eq(clean(' v2.44.1 '), '2.44.1')
  eq(clean('2.2.3-beta+build.7'), '2.2.3-beta+build.7')
  eq(clean('version'), 'version')
  eq(clean(''), nil)
  eq(clean(nil), nil)
  eq(clean('1.0 beta'), nil)
  eq(clean('-1.0'), nil)
  eq(clean(('9'):rep(33)), nil)
  eq(clean(('9'):rep(32)), ('9'):rep(32))
end)

test('a missing version is reported as unknown', function()
  Stub.resources['qbx_core'] = { state = 'started', meta = {} }
  Stub.start('ox_inventory', '2.44.1')
  local cap = Aptic.capability.detect()
  eq(cap.framework_version, nil)
  eq(Aptic.capability.describe(cap), 'qbox (version unknown) + ox_inventory 2.44.1')
end)
